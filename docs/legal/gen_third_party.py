#!/usr/bin/env python3
"""Regenerates the Rust crate tables in third-party-notices.md.

Usage (from the repo root):

    cargo metadata --format-version 1 --filter-platform x86_64-unknown-linux-gnu > /tmp/dfte-linux.json
    cargo metadata --format-version 1 --filter-platform aarch64-linux-android > /tmp/dfte-android.json
    python3 docs/legal/gen_third_party.py /tmp/dfte-linux.json /tmp/dfte-android.json

It rewrites the text between the "crates:begin" and "crates:end" markers in
third-party-notices.md and leaves the rest of the file alone.

Which crates count: everything reachable from the shipped binaries (dfte-cli and
dfte-gtk on Linux, platform-ffi on Android) through normal dependency edges.
Build-script dependencies and proc-macro crates (and anything reached only
through them) run on the build machine and are not part of the app, so they are
left out, as are dev-dependencies.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

LINUX_ROOTS = ["dfte-cli", "dfte-gtk"]
ANDROID_ROOTS = ["platform-ffi"]
NOTICES = Path(__file__).with_name("third-party-notices.md")
BEGIN = "<!-- crates:begin (generated by gen_third_party.py, do not edit by hand) -->"
END = "<!-- crates:end -->"


def shipped(metadata_path, roots):
    m = json.loads(Path(metadata_path).read_text())
    pkgs = {p["id"]: p for p in m["packages"]}
    members = set(m["workspace_members"])
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}

    def proc_macro(pid):
        return any("proc-macro" in t["kind"] for t in pkgs[pid]["targets"])

    start = [pid for pid in members if pkgs[pid]["name"] in roots]
    if len(start) != len(roots):
        sys.exit(f"could not find all of {roots} among the workspace members")
    out, stack = set(), list(start)
    while stack:
        pid = stack.pop()
        if pid in out or proc_macro(pid):
            continue
        out.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return {
        (pkgs[p]["name"], pkgs[p]["version"]): pkgs[p]["license"] or "see the crate's license file"
        for p in out
        if p not in members
    }


def normalize(expr):
    """Puts plain "A OR B" expressions in a fixed order so equal ones group together."""
    expr = expr.replace("/", " OR ")
    if "(" in expr or " AND " in expr or " WITH " in expr:
        return expr
    return " OR ".join(sorted(t.strip() for t in expr.split(" OR ")))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    linux = shipped(sys.argv[1], LINUX_ROOTS)
    android = shipped(sys.argv[2], ANDROID_ROOTS)

    groups = defaultdict(list)
    for key in sorted(set(linux) | set(android)):
        lic = normalize(linux.get(key) or android[key])
        where = "both" if key in linux and key in android else ("Linux" if key in linux else "Android")
        groups[lic].append((key[0], key[1], where))

    lines = [
        BEGIN,
        "",
        f"{len(set(linux) | set(android))} crates in total: {len(linux)} in the Linux apps, "
        f"{len(android)} in the Android library. \"Used in\" says which build includes the crate.",
        "",
    ]
    for lic in sorted(groups, key=lambda g: (-len(groups[g]), g)):
        rows = groups[lic]
        lines += [f"### {lic} ({len(rows)})", "", "| Crate | Version | Used in |", "|---|---|---|"]
        lines += [f"| {n} | {v} | {w} |" for n, v, w in rows]
        lines.append("")
    lines.append(END)

    text = NOTICES.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f"markers not found in {NOTICES}")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    NOTICES.write_text(head + "\n".join(lines) + tail)


if __name__ == "__main__":
    main()
